// Fetch Live News generated by Python daily_runner.py, database.py & excel_sync.py
async function fetchLiveNewsFeed() {
    try {
        // Try fetching from persistent SQLite database endpoint first, fallback to JSON
        let liveData = null;
        try {
            const dbResp = await fetch('/api/database/articles?limit=50&t=' + Date.now());
            if (dbResp.ok) {
                const dbJson = await dbResp.json();
                if (Array.isArray(dbJson.articles) && dbJson.articles.length > 0) {
                    liveData = dbJson.articles;
                    console.log("[+] Loaded news directly from SQLite news.db!");
                }
            }
        } catch (_) {}

        if (!liveData) {
            const response = await fetch('news_feed.json?t=' + Date.now());
            if (response.ok) {
                liveData = await response.json();
            }
        }

        if (Array.isArray(liveData) && liveData.length > 0) {
            console.log("[+] Live news payload loaded successfully!");
            newsDatabase = liveData.map((item, idx) => ({
                id: item.id || idx + 1,
                headline_en: item.headline_en || item.title || "Sri Lanka Business Update",
                headline_si: item.headline_si || item.title_si || item.headline_en,
                category: item.category || "Business & Governance",
                source: item.source || "Daily FT (ft.lk)",
                date: item.published_at || item.scraped_at || "Today",
                published_at: item.published_at || item.scraped_at || "Today",
                readTime: "3 min read",
                image: item.image || item.image_url || "https://bmkltsly13vb.compat.objectstorage.ap-mumbai-1.oraclecloud.com/cdn.ft.lk/ftlk_logo_og.png",
                summary_en: item.summary_en || item.summary || "",
                summary_si: item.summary_si || item.summary_en || "",
                content: item.passive_voice_content || item.content || item.summary_en || "",
                passive_voice_content: item.passive_voice_content || item.content || item.summary_en || "",
                key_takeaways: item.key_takeaways || item.takeaways || ["Scraped & AI processed."],
                isHero: idx === 0
            }));
        }
    } catch (e) {
        console.log("[-] Using default offline news state:", e);
    }
}


function renderNews() {
    let filtered = newsDatabase;
    
    // Category Filter
    if (activeCategory !== 'all') {
        filtered = newsDatabase.filter(item => {
            const catLower = (item.category || '').toLowerCase();
            return catLower.includes(activeCategory.toLowerCase());
        });
    }
    
    // Search Filter
    const searchVal = searchInput.value.trim().toLowerCase();
    if (searchVal) {
        filtered = filtered.filter(item => 
            (item.headline_en || '').toLowerCase().includes(searchVal) || 
            (item.summary_en || '').toLowerCase().includes(searchVal)
        );
    }

    if (filtered.length === 0) {
        heroArticleContainer.style.display = 'none';
        secondaryArticlesContainer.innerHTML = '<div style="grid-column: 1/-1; padding: 40px; text-align: center; color: var(--text-muted);">No articles found for selected category.</div>';
        return;
    }

    // Identify Hero Article
    const hero = filtered.find(a => a.isHero) || filtered[0];
    const secondaries = filtered.filter(a => a.id !== hero.id);

    // Render Hero
    heroArticleContainer.style.display = 'grid';
    const titleText = currentLang === 'si' ? (hero.headline_si || hero.headline_en) : hero.headline_en;
    const summaryText = currentLang === 'si' ? (hero.summary_si || hero.summary_en) : hero.summary_en;

    heroArticleContainer.innerHTML = `
        <div class="hero-img-wrap">
            <img src="${hero.image}" alt="${titleText}">
            <span class="category-tag">${hero.category}</span>
        </div>
        <div class="hero-info">
            <div class="meta-info">
                <span><i class="fa-regular fa-clock"></i> ${hero.date}</span> &bull; 
                <span>${hero.readTime}</span>
            </div>
            <h1><a href="#" onclick="openArticleModal('${hero.id}'); return false;">${titleText}</a></h1>
            <p>${summaryText}</p>
            
            <div class="ai-summary-box">
                <i class="fa-solid fa-sparkles text-primary"></i> <strong>Groq AI Takeaway:</strong>
                ${hero.key_takeaways ? (Array.isArray(hero.key_takeaways) ? hero.key_takeaways[0] : hero.key_takeaways) : 'Key financial disclosure updates.'}
            </div>

            <div>
                <button class="btn btn-primary" onclick="openArticleModal('${hero.id}')">
                    Read Full Coverage <i class="fa-solid fa-arrow-right"></i>
                </button>
            </div>
        </div>
    `;

    // Render Secondaries
    secondaryArticlesContainer.innerHTML = secondaries.map(art => {
        const artTitle = currentLang === 'si' ? (art.headline_si || art.headline_en) : art.headline_en;
        const artSummary = currentLang === 'si' ? (art.summary_si || art.summary_en) : art.summary_en;
        return `
            <article class="card article-card">
                <div>
                    <div class="article-thumb">
                        <img src="${art.image}" alt="${artTitle}">
                    </div>
                    <div class="meta-info">
                        <span class="category-tag" style="position:static; display:inline-block; margin-bottom: 6px;">${art.category}</span>
                        &bull; ${art.date}
                    </div>
                    <h3><a href="#" onclick="openArticleModal('${art.id}'); return false;">${artTitle}</a></h3>
                    <p>${artSummary.substring(0, 140)}...</p>
                </div>
                <button class="btn btn-secondary" onclick="openArticleModal('${art.id}')" style="align-self: flex-start; margin-top: 10px; font-size: 0.775rem;">
                    Read Article &rarr;
                </button>
            </article>
        `;
    }).join('');

    // Render Sidebar Governance Feed
    const govArticles = newsDatabase.slice(0, 4);
    govFeedContainer.innerHTML = govArticles.map(g => {
        const gTitle = currentLang === 'si' ? (g.headline_si || g.headline_en) : g.headline_en;
        return `
            <div class="gov-feed-item">
                <h4><a href="#" onclick="openArticleModal('${g.id}'); return false;">${gTitle}</a></h4>
                <div class="time-meta"><i class="fa-regular fa-clock"></i> Daily FT Scraped | Groq AI Ingested</div>
            </div>
        `;
    }).join('');
}

function setupEventListeners() {
    // Category Navigation
    document.querySelectorAll('.nav-link').forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            document.querySelectorAll('.nav-link').forEach(l => l.classList.remove('active'));
            link.classList.add('active');
            activeCategory = link.getAttribute('data-category');
            renderNews();
        });
    });

    // Language Toggle
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            currentLang = btn.getAttribute('data-lang');
            renderNews();
        });
    });

    // Theme Toggle
    const themeBtn = document.getElementById('themeToggle');
    themeBtn.addEventListener('click', () => {
        document.body.classList.toggle('dark-theme');
        const icon = themeBtn.querySelector('i');
        if (document.body.classList.contains('dark-theme')) {
            icon.className = 'fa-solid fa-sun';
        } else {
            icon.className = 'fa-solid fa-moon';
        }
    });

    // Search Input
    searchInput.addEventListener('input', () => {
        renderNews();
    });

    // Pipeline Panel Toggle
    pipelineToggleBtn.addEventListener('click', () => {
        pipelineSection.classList.toggle('hidden');
        if (!pipelineSection.classList.contains('hidden')) {
            pipelineSection.scrollIntoView({ behavior: 'smooth' });
        }
    });

    // Run Live Scraper
    runScraperBtn.addEventListener('click', triggerLiveScraperRun);

    // Code Modal
    viewCodeBtn.addEventListener('click', () => {
        codeModal.classList.add('active');
    });

    codeModalCloseBtn.addEventListener('click', () => {
        codeModal.classList.remove('active');
    });

    modalCloseBtn.addEventListener('click', () => {
        articleModal.classList.remove('active');
    });
}

// Live News Scraper & AI Trigger
async function triggerLiveScraperRun() {
    runScraperBtn.disabled = true;
    runScraperBtn.innerHTML = '<i class="fa-solid fa-spinner fa-spin"></i> Running Daily FT & Groq AI Pipeline...';
    scraperConsoleLog.innerText = "[*] Connecting to live scraper pipeline...\n";

    try {
        const triggerResp = await fetch('/api/scraper/trigger?source=web-dashboard', { method: 'POST' });
        const triggerData = await triggerResp.json();
        scraperConsoleLog.innerText += `[+] ${triggerData.message || 'Scraper pipeline initiated'}\n`;

        // Poll pipeline status
        const pollInterval = setInterval(async () => {
            try {
                const statusResp = await fetch('/api/scraper/status');
                const statusData = await statusResp.json();

                if (Array.isArray(statusData.recentOutput) && statusData.recentOutput.length > 0) {
                    scraperConsoleLog.innerText = statusData.recentOutput.join('\n');
                    scraperConsoleLog.scrollTop = scraperConsoleLog.scrollHeight;
                }

                if (!statusData.running) {
                    clearInterval(pollInterval);
                    runScraperBtn.disabled = false;
                    runScraperBtn.innerHTML = '<i class="fa-solid fa-play"></i> Trigger Live Daily FT Scraper';
                    scraperConsoleLog.innerText += "\n[+] Pipeline completed! Refreshing news portal...\n";
                    await fetchLiveNewsFeed();
                    renderNews();
                }
            } catch (err) {
                console.warn("[i] Polling notice:", err);
            }
        }, 2500);
    } catch (err) {
        scraperConsoleLog.innerText += `[-] Error: ${err.message}\n`;
        runScraperBtn.disabled = false;
        runScraperBtn.innerHTML = '<i class="fa-solid fa-play"></i> Trigger Live Daily FT Scraper';
    }
}

